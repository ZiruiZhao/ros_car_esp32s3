#pragma once

#include <Arduino.h>

// ============================================================================
// 里程计 —— 航位推算（dead reckoning）
//
//   编码器数轮子转了多少 → 车走了多远；姿态解算给出车头朝哪 → 把「走了多远」
//   投影到 x/y 上。合起来回答「车现在在哪、朝哪」，这是导航的起点。
//
//   ---- 为什么叫「推算」（dead reckoning）----
//
//   因为它**没有绝对参考**，全靠从已知起点一步步积出来。每一步的误差都留在
//   结果里，只会越积越大 —— 这和步骤 5 里 yaw 纯积分会漂是同一个道理，不是
//   代码没写好，是方法本身的性质。
//
//   所以里程计**必须定时重来**：回到已知位置（充电桩、二维码、激光雷达匹配到）
//   就 odom_reset() 一次。ROS2 里这也是标准做法（AMCL 重定位后重置 odom）。
//
//   ---- 是右手系，与车体坐标系一致 ----
//
//     x  正 = 车头方向（起始朝向前方）
//     y  正 = 车体左侧
//     θ  正 = 左转（俯视逆时针），与 attitude 的 yaw、chassis 的 w>0 同号
//
//   所以「车头朝 θ 方向走 d」就是 x += d·cos(θ)、y += d·sin(θ)。
//   三处符号约定一致，这里不需要任何转换 —— 这是步骤 5 特意对齐过的好处。
//
//   ---- 用中点航向积分，不用欧拉积分 ----
//
//   走直线时两种积分完全一样，但**边走边转时差别很大**：
//
//     欧拉：  x += d·cos(θ_旧)          ← 用这一小段起点处的航向，永远差半拍
//     中点：  x += d·cos(θ_旧 + Δθ/2)   ← 用这一小段弧中间点的航向
//
//   欧拉的误差来自**航向滞后半拍**：它拿「转弯前」的朝向去投影这一段的位移，
//   于是整条轨迹被拽向弯道内侧。这个偏差是系统性的，不会自己抵消 ——
//   仿真实测（R=50cm 边走边转 90°）：欧拉端点偏 3.08cm，中点偏 0.03cm，**98 倍**。
//
//   ⚠ 这里有个非常容易骗过人的陷阱：**绕整整一圈时，欧拉的误差会归零**。
//   整圈的各段航向均匀铺满 0~360°，cos/sin 求和天然抵消，两种方法都严丝合缝
//   回到原点。所以「绕圈闭不闭合」根本测不出这个 bug —— 必须测**一段**圆弧
//   （45°/90°/180° 都行）。实测误差随扫过角度：45°→1.67cm、90°→3.08cm、
//   180°→4.36cm、360°→0.00cm。
//
//   中点法剩下的那 0.03cm 不是方法误差，是「把圆弧当折线走」的弦离散化残差，
//   段越细越小，换任何积分方法都有。
//
//   这不是精度问题，是走圆弧会不会系统性跑偏的问题。仿真见开发流程.md 步骤 7。
//
//   ---- 航向 θ 用 IMU 的 yaw，不用编码器差速推算 ----
//
//   编码器也能算航向：θ = (d右 - d左) / 轮距。但两个原因让它现在不可用：
//     ① **轮距没标定** —— wheel_encoder.h 里只有轮径，没有左右轮中心距。
//        差速算航向对轮距是**线性敏感**的，轮距错 20%，转 90° 就错 18°。
//     ② **打滑直接污染它** —— 编码器只知道轮子转了多少，不知道车有没有真的动。
//        原地打滑时它照样在积分航向。
//
//   而 yaw 是陀螺仪直接测的，不依赖任何几何常数，也不怕打滑。代价是长时间漂
//   （没有磁力计）—— 但这是「慢慢漂」和「系统性错」的区别，前者可控。
//
//   本模块用 IMU 的 yaw **增量**（Δyaw）而不是绝对值，好处是 yaw 归零（0x26 帧）
//   不会把里程计带歪 —— 增量不受零点变化影响。车停着时
//   attitude 会冻结 yaw（静止修正），Δyaw=0，里程计跟着不动，天然对齐。
//
//   ---- ⚠ 距离刻度必须实测标定 ----
//
//   走多远 = 编码器计数 × 每计数多少厘米，而
//
//     每计数厘米 = 轮径 × π / 每转计数
//
//   这两个因子在 wheel_encoder.h 里都是**标称值，没有实测过**。它们只以乘积形式
//   进入公式，所以一个系数就能全部修正 —— 那就是 ODOM_DIST_SCALE。
//
//   标定方法（30 秒，比拿卡尺量轮径 + 转 10 圈数计数快得多）：
//     1. 发 0x29 帧归零里程计，把车摆正
//     2. 沿卷尺走一段已知距离（建议 100cm 以上，越长越准），走直线
//     3. 发 0x27 帧读 dist 字段，假设读到 92.3
//     4. 发 0x2A 帧存 1.083（= 100 / 92.3，量化 ×10000 即 10830），再走一遍验证
//
//   ⚠ 默认值 1.0 **没有意义**，只是「未标定」的意思。不标定的话，走 1 米可能
//     报成 90cm 或 110cm —— 而且这个错是**系统性**的，走越远偏越多。
// ============================================================================

// 更新周期：50ms，与底盘闭环节拍一致。
// 挂在闭环节拍上而不是自己计时，是为了让「读编码器」和「控电机」用同一拍的数据，
// 否则两者之间会差一拍，原地转时位置会画成锯齿。
static constexpr uint32_t ODOM_PERIOD_US = 50000U;

// 距离刻度修正系数。1.0 = 用 wheel_encoder.h 里那两个标称常数的原始值。
// ⚠ 这是**唯一必须实测**的里程计参数，标定方法见上。
static constexpr float ODOM_DIST_SCALE_DEFAULT = 1.0f;
static constexpr float ODOM_DIST_SCALE_MIN = 0.2f;
static constexpr float ODOM_DIST_SCALE_MAX = 5.0f;

// 里程计状态快照
struct OdomState {
  float x_cm;       // 位置（cm），起点为原点
  float y_cm;
  float theta_deg;  // 航向（度），起点朝向为 0
  float dist_cm;    // 累计路程（cm，只增不减）—— 标定刻度系数就靠它
  float v_cm_s;     // 线速度估计（左右轮平均）
  float w_dps;      // 角速度估计（°/s，正 = 左转）
  bool valid;       // false = 数据还不够，此时 x/y/θ 都没意义
};

void odom_init();

// 每 ODOM_PERIOD_US 调一次。返回 true = 本次真的更新了位姿。
//
// 时机：必须在 chassis_update() 之后调（它要读编码器计数）。挂在主循环里
// attitude_update() 之后最合适 —— 那样这一拍的新编码器和刚解算出的 yaw 是配套的，
// 两者相乘投影时不会差一拍。见 main.cpp 的 loop()。
bool odom_update();

OdomState odom_get();

// 把当前位置记为原点、当前朝向记为 0（内部会记下当前 yaw 作增量的基准）。
// 回到已知位置时调一次，是抑制累积误差的标准手段。
void odom_reset();

// ---- 标定 / 调参 ----
void odom_set_dist_scale(float scale);
float odom_get_dist_scale();

// 里程计是否可用（姿态数据就绪后才为 true）
bool odom_is_ready();
