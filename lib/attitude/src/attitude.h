#pragma once

#include <Arduino.h>
#include <imu_mpu6050.h>

// ============================================================================
// 姿态解算 —— 互补滤波（陀螺仪 + 加速度计）
//
//   要解决的核心矛盾：
//     陀螺仪  ：短期准、响应快，但积分会累积漂移（零偏和噪声全被积进去）
//     加速度计：长期准（重力方向是绝对参考），但动态时被车体加减速污染，抖
//   互补滤波按频率分工：陀螺仪管高频（快），加速度计管低频（慢）
//
//     angle = α · (angle + gyro_rate·dt) + (1-α) · angle_acc
//             └────── 陀螺积分：预测 ──────┘   └──── 加速度计：校正 ────┘
//
//   α 越大越信陀螺（响应快、不容易被加减速带偏，但陀螺零偏校不回来）。
//   时间常数 τ = α·dt/(1-α)；本工程 α=0.98、dt=10ms → τ ≈ 0.49s。
//
//   ⚠ yaw 没有校正项。MPU6050 没有磁力计，重力方向在水平面上不提供任何信息，
//     所以 yaw 只能纯积分、必然漂移。漂移率就是残余零偏：标定后实测 gz 残差
//     约 +0.02°/s，对应约 1.2°/min；这就是它的量级，不是代码没写好。
//     详见 imu_mpu6050.h 顶部。
//
//   ---- 坐标约定（车体坐标系，右手系：X 前 × Y 左 = Z 上）----
//     roll_deg   绕 X 轴，正 = 车身左侧抬起
//     pitch_deg  绕 Y 轴，正 = 车头上仰（爬坡）
//     yaw_deg    绕 Z 轴，正 = 左转（俯视逆时针），与 chassis 的 w>0 同号
//
//   模块必须平放在车体上、X 轴指向车头、Z 轴朝上，否则不是「角度不准」而是
//   「轴全串了」。在动参数之前先确认摆放。
// ============================================================================

// 解算周期：100Hz，与 IMU 输出率对齐。
// 节拍门限做在模块内部，而不是让调用方每圈都调 —— 因为每次解算都要读一次
// I2C（14 字节，约 0.4ms）。loop() 每秒跑几万次，不加门限就是几万次 I2C 读，
// 总线被占满，底盘闭环和串口全被拖慢。
static constexpr uint32_t ATTITUDE_PERIOD_US = 10000U;

// 互补滤波系数 α 默认值。τ = α·dt/(1-α)，α=0.98、dt=10ms → τ≈0.49s。
// 角度被加减速带偏 → 调小；响应太慢、角度跟不上车体 → 调大。
static constexpr float ATTITUDE_ALPHA_DEFAULT = 0.98f;
static constexpr float ATTITUDE_ALPHA_MIN = 0.50f;
static constexpr float ATTITUDE_ALPHA_MAX = 0.999f;

// dt 上限：loop 卡顿导致 dt 突然变大时夹到这里（正常 dt 是 10ms）。
// 宁可少积一点（角度偏小）也不要一次跳一大截（角度乱飞）。
static constexpr float ATTITUDE_DT_MAX_S = 0.05f;

// 加速度计可信区间：|a| 必须落在这里面才用它做校正。
// 车体急加速/急刹/撞击时 |a| 会明显偏离 1g，那时刻的「重力方向」是假的，
// 拿它校正会让 roll/pitch 猛地一甩。超出区间时只信陀螺，等回到区间内再校正。
static constexpr float ATTITUDE_ACCEL_MAG_MIN = 0.5f;
static constexpr float ATTITUDE_ACCEL_MAG_MAX = 1.5f;

// ============================================================================
//  静止修正 —— 零速修正（冻结 yaw）+ 零偏在线跟踪
//
//   为什么非做不可：MPU6050 的零偏**不是常数**。本工程实测过一次，24 分钟里
//   Z 轴零偏从开机标定时的 +0.02°/s 漂到了 -1.05°/s —— 光靠开机标定压不住，
//   yaw 会一路积到上千度（-1.07°/s × 24min ≈ -1500°，和实测完全对上）。
//   温度也排查过了，29°C 稳定不变，与温漂无关，就是芯片自身的零偏不稳定。
//
//   做法：车确实停着的时候
//     ① 冻结 yaw 积分 —— 停着就不该有转角
//     ② 把零偏估计缓慢拉向当前陀螺读数（时间常数 ATTITUDE_BIAS_TRACK_TAU_S）
//   于是停着的时候零偏被自动校准，下次开动时用的是新鲜零偏。
//
//   「停着」= 调用方说车轮没转（编码器）+ 陀螺读数很小（没人用手转它）。
//   两个条件缺一不可：只看编码器的话，「把车架空用手转」会被误判成静止，
//   零偏跟踪会把真实转角当成零偏吃掉，yaw 就彻底不涨了。
//
//   ⚠ 代价：慢于 ATTITUDE_STILL_GYRO_DPS 的手动旋转会被当成静止而冻结。
//     手转车验证时正常速度转（90° 大约 1~2 秒）远高于这个阈值，不受影响。
// ============================================================================

// 陀螺「安静」阈值：三轴合矢量小于它才算没在转。
//
// ⚠ 这个判据衡量的其实是**零偏估计的残差**，不是「车有没有在转」—— 因为
// s.gyro_* 是已经扣过零偏的读数（见 imu_mpu6050.cpp 的 imu_read）。而零偏跟踪
// 又只在判定为「静止」时才跑，两者互为入场条件，于是闭成一个环：
//
//     零偏漂过这个阈值 → 永远判不出静止 → 零偏永远不被修正 → 零偏永远漂
//
// 这是个自锁：一旦锁上，唯一能救零偏的机制恰好被零偏自己锁死了。
//
// ⚠ 解除自锁只能重新标定零偏（0x22 号帧）。yaw 归零（0x26）对自锁毫无作用 ——
//   attitude_zero_yaw() 只清 yaw，一个字节都不碰零偏。
//
// 阈值取 3.0 太薄：本工程实测零偏漂到过 1.05°/s，而这里是三轴合矢量
// （三个轴的残差一起算），余量还要再打折扣。6.0 给自锁留出 2 倍余量 ——
// 零偏即便漂到这个量级，仍能被判成静止，零偏跟踪重新启动，τ=10s 内把残差
// 自己拉回来（自愈）。
static constexpr float ATTITUDE_STILL_GYRO_DPS = 6.0f;

// 静止要连续维持这么久才生效，避免行驶中短暂停顿就触发
static constexpr uint32_t ATTITUDE_STILL_DELAY_US = 500000U;

// 零偏跟踪时间常数。太大跟不上零偏漂移，太小会把噪声学进零偏里。
// 10 秒：停下来 10 秒左右零偏就基本收敛，比手动重跑一次标定还快。
static constexpr float ATTITUDE_BIAS_TRACK_TAU_S = 10.0f;

// 姿态角快照（单位：度）
struct Attitude {
  float roll_deg;
  float pitch_deg;
  float yaw_deg;   // 累计值，不折回 ±180 —— 掉头就是 180，转两圈就是 720，便于直接判读
  bool valid;      // false = 还没攒够 IMU 数据，此时三个角都没有意义

  // 本拍用的 Z 轴角速度（°/s，已扣零偏）。
  // 单独带出来是给转向环当阻尼项用的：转向环需要「当前转得多快」，
  // 而它对角度求差分得到的值噪声很大；陀螺仪读数是直接测量，干净得多。
  float gyro_z_dps;
};

// 初始化（角度清零、节拍基准归零）
void attitude_init();

// 在 loop() 里调用。内部自带 100Hz 节拍门限，未到周期直接返回 false 且不读 I2C。
// 返回 true = 本次刷新了姿态角。
//
// vehicle_stopped：车是否停着（由调用方按编码器速度判断）。
// 解算层不认识底盘，所以这个信息必须从外面传进来 —— 见上面「静止修正」。
bool attitude_update(bool vehicle_stopped);

// 当前是否处于「静止修正」状态：yaw 冻结中 + 零偏正在被跟踪。
// 验证静止修正是否生效就看它。
bool attitude_is_still();

// 取当前姿态
Attitude attitude_get();

// 把当前 yaw 记为 0（把「现在车头朝向」当作基准方向）。
// 注意：只清零 yaw，不动 roll/pitch —— 后两者是绝对角度，不该被重置。
void attitude_zero_yaw();

// 在线整定互补滤波系数（不必重新烧录）
void attitude_set_alpha(float alpha);
float attitude_get_alpha();

// 上次解算用的 dt（秒）。调参时用来看「loop 有没有卡」。
float attitude_get_dt_s();

// 实测解算频率（Hz，每秒统计一次）。明显低于 100 说明 loop 被别的东西拖慢了。
uint16_t attitude_get_rate_hz();
